    static func definition(for id: String?) -> MerchantBrandDefinition? {
        guard let id else { return nil }
        return definitions.first { $0.id == id }
    }

    static func isConvenienceStoreBrand(_ brand: MerchantBrandDefinition) -> Bool {
        convenienceStoreBrandIDs.contains(brand.id)
    }

    static func isConvenienceStoreBrand(id: String?) -> Bool {
        guard let brand = definition(for: id) else { return false }
        return isConvenienceStoreBrand(brand)
    }

    static func matchBrand(in text: String) -> MerchantBrandDefinition? {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return nil }

        var matches: [MerchantBrandAliasMatch] = []
        for brand in definitions {
            for alias in brand.aliases {
                matches.append(MerchantBrandAliasMatch(brand: brand, alias: alias))
            }
        }

        matches.sort { lhs, rhs in
            if lhs.alias.count == rhs.alias.count {
                return lhs.brand.id < rhs.brand.id
            }
            return lhs.alias.count > rhs.alias.count
        }

        return matches.first { containsAlias($0.alias, in: trimmed) }?.brand
    }

    static func isExactBrandAlias(_ text: String, for brandId: String) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard let brand = definition(for: brandId), !trimmed.isEmpty else { return false }
        return brand.aliases.contains { alias in
            alias.caseInsensitiveCompare(trimmed) == .orderedSame
        } || brand.displayName.caseInsensitiveCompare(trimmed) == .orderedSame
    }

    static func matchOCRBrand(in text: String) -> MerchantBrandDefinition? {
        if let brand = matchBrand(in: text) {
            return brand
        }
        let folded = text
            .lowercased()
            .replacingOccurrences(of: " ", with: "")
            .replacingOccurrences(of: "\n", with: "")
        let luckinSignals = ["luckincoffee", "蓝杯", "小蓝杯"]
        if luckinSignals.contains(where: { folded.contains($0) }) {
            return definition(for: "luckin")
        }
        return nil
    }

