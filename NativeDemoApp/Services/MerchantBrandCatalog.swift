    static func definition(for id: String?) -> MerchantBrandDefinition? {
        guard let id else { return nil }
        return definitions.first { $0.id == id }
    }

    static func matchBrand(in text: String) -> MerchantBrandDefinition? {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return nil }
        let matches = definitions.flatMap { brand in
            brand.aliases.map { alias in (brand: brand, alias: alias) }
        }
        .sorted { lhs, rhs in
            lhs.alias.count == rhs.alias.count ? lhs.brand.id < rhs.brand.id : lhs.alias.count > rhs.alias.count
        }
        return matches.first { containsAlias($0.alias, in: trimmed) }?.brand
    }

    private static func brand(
        _ id: String,
        _ displayName: String,
        _ aliases: [String],
        _ category: HomeItem.Category,
        _ tierNotes: [[String]]
    ) -> MerchantBrandDefinition {
        let limits: [Double] = [20, 50, 120, 9_999]
        let tiers = zip(limits, tierNotes).map { ScenePackTier(maxAmount: $0.0, notes: $0.1) }
        return MerchantBrandDefinition(
            id: id,
            displayName: displayName,
            aliases: aliases,
            category: category,
            tiers: tiers
        )
    }

    private static func containsAlias(_ alias: String, in text: String) -> Bool {
        let trimmed = alias.trimmingCharacters(in: .whitespacesAndNewlines)
        guard trimmed.count >= 2 else { return false }
        if trimmed.range(of: #"\p{Han}"#, options: .regularExpression) != nil {
            return text.localizedCaseInsensitiveContains(trimmed)
        }

        let target = trimmed.lowercased()
        let folded = text.lowercased()
        if target.count <= 3,
           target.range(of: #"^[a-z0-9]+$"#, options: .regularExpression) != nil {
            let tokens = folded.components(separatedBy: CharacterSet.alphanumerics.inverted)
            return tokens.contains(target)
        }
        return folded.contains(target)
    }
